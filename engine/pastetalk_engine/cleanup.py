"""Отсев того, чего человек не говорил.

Whisper обучали на огромном массиве видеосубтитров, и в тишине он
достраивает самое вероятное продолжение — а самым вероятным «текстом
там, где ничего не сказано» в его обучении оказались подписи
переводчиков и концовки роликов. Отсюда «Субтитры создавал DimaTorzok»,
«Продолжение следует…» и «Спасибо за просмотр!» посреди диктовки.

Отсеиваем двумя способами сразу.

Первый — по списку: эти фразы всплывают буквально дословно, их видели
тысячи людей, и совпадение с ними в надиктованном тексте практически
всегда означает выдумку.

Второй — по уверенности модели. У каждого куска Whisper сообщает,
насколько он считает его тишиной (no_speech_prob) и насколько уверен в
словах (avg_logprob). Выдумка выдаёт себя сочетанием: «здесь тишина» и
«я не уверен» одновременно. Живая речь так не выглядит даже при плохом
микрофоне.
"""

from __future__ import annotations

import re

# Фразы целиком. Сравниваем по нормализованному виду: без регистра,
# знаков препинания и лишних пробелов.
_EXACT = {
    "продолжение следует",
    "продолжение следует...",
    "спасибо за просмотр",
    "спасибо за внимание",
    "подписывайтесь на канал",
    "подписывайся на канал",
    "ставьте лайки и подписывайтесь на канал",
    "не забудьте подписаться",
    "всем пока",
    "до новых встреч",
    "приятного просмотра",
    "редактор субтитров",
    "субтитры",
    "конец",
    "the end",
    "thanks for watching",
    "thank you for watching",
    "please subscribe",
    "see you next time",
    "bye",
}

# Подписи субтитровщиков и площадок. Достаточно встретить внутри куска.
_SIGNATURES = (
    "dimatorzok",
    "субтитры создавал",
    "субтитры создал",
    "субтитры сделал",
    "субтитры делал",
    "субтитры подготовил",
    "редактор субтитров",
    "корректор а.",
    "субтитры и перевод",
    "перевод и субтитры",
    "amara.org",
    "subtitles by",
    "subs by",
    "проект «мир",
    "игорь негода",
)

_PUNCT = re.compile(r"[^\w\s]", re.UNICODE)
_SPACES = re.compile(r"\s+")

# Порог «модель сама не верит в этот кусок». Числа подобраны так, чтобы
# не трогать живую речь: у настоящих фраз no_speech_prob обычно сильно
# ниже, даже когда человек говорит тихо.
_NO_SPEECH = 0.7
_LOW_CONFIDENCE = -0.9


def _normalise(text: str) -> str:
    return _SPACES.sub(" ", _PUNCT.sub("", text.lower())).strip()


def looks_invented(text: str, no_speech_prob: float = 0.0, avg_logprob: float = 0.0) -> str:
    """Причина, по которой кусок стоит выбросить, или пустая строка."""
    normalised = _normalise(text)
    if not normalised:
        return "пусто"

    for signature in _SIGNATURES:
        if signature in normalised:
            return f"подпись субтитров: {signature}"

    if normalised in _EXACT:
        return "типовая концовка ролика"

    # Модель одновременно считает кусок тишиной и не уверена в словах.
    if no_speech_prob >= _NO_SPEECH and avg_logprob <= _LOW_CONFIDENCE:
        return f"тишина по мнению модели (no_speech {no_speech_prob:.2f}, logprob {avg_logprob:.2f})"

    return ""


def keep(segment) -> str:
    """Пустая строка — кусок выбрасываем, иначе возвращаем его текст."""
    text = (segment.text or "").strip()
    reason = looks_invented(
        text,
        getattr(segment, "no_speech_prob", 0.0) or 0.0,
        getattr(segment, "avg_logprob", 0.0) or 0.0,
    )
    return "" if reason else text
